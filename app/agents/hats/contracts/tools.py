"""Tools owned by the contracts hat.

Generated by scripts/move_tool_branches.py from Agent._run_tool_call
(F-DRIVER Phase A); each registers itself with app.agents.core.tool_registry.
"""
from __future__ import annotations

from app.agents.core.tool_registry import ToolCall, tool
from app.lib.formula_registry import Param


@tool(
    "rfi_generator",
    owner="contracts",
    display_name="RFI drafter",
    params={
        "issues": Param(label="issues to raise", kind="list", required=False),
        "drawing_ref": Param(label="drawing", kind="text", required=False),
        "project_name": Param(label="project", kind="text", required=False),
        "contractor_name": Param(label="contractor", kind="text", required=False),
        "engineer_name": Param(label="engineer", kind="text", required=False),
        "start_number": Param(
            unit="count", lo=1, hi=1_000_000, label="first number",
            kind="integer", required=False,
        ),
        "text": Param(label="question", kind="text", required=False),
    },
)
async def handle_rfi_generator(call: ToolCall) -> dict:
    """The ``rfi_generator`` tool."""
    from app.agents.runtime import (  # noqa: F401 -- runtime helpers, imported at call time
        Any,
    )
    args = call.args
    name = call.name
    agent = call.agent
    user_message = call.user_message
    if "construction" not in agent.allowed_blocks:
        return {
            "name": name,
            "ok": False,
            "result": {
                "status": "error",
                "error": "construction container not in agent's allowed_blocks",
            },
        }
    try:
        from app.dependencies import get_block_instance
        container = get_block_instance("construction")
    except Exception as e:
        return {
            "name": name,
            "ok": False,
            "result": {"status": "error", "error": f"construction unavailable: {e}"},
        }
    params: dict[str, Any] = {}
    nested = args.get("params")
    if isinstance(nested, dict):
        params.update(nested)
    for key in (
        "issues", "drawing_ref", "project_name",
        "contractor_name", "engineer_name", "start_number",
        "text", "user_message",
    ):
        if args.get(key) is not None:
            params.setdefault(key, args.get(key))
    input_data = args.get("input")
    if not isinstance(input_data, dict):
        input_data = {}
    else:
        input_data = dict(input_data)
    input_data.setdefault(
        "message", args.get("message") or user_message or "",
    )
    params.setdefault("user_message", input_data.get("message") or "")
    params.setdefault("text", input_data.get("message") or "")
    try:
        result = await container.rfi_generator(
            input_data, params,
        )
    except Exception as e:
        return {
            "name": name,
            "ok": False,
            "result": {
                "status": "error",
                "error": f"rfi_generator failed: {e}",
            },
        }
    return {
        "name": "rfi_generator",
        "ok": isinstance(result, dict) and result.get("status") == "success",
        "result": result,
    }
