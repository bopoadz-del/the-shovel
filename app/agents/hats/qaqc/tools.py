_SPLIT_NAMES = re.compile(r"\s*(?:,|;|/|\band\b)\s*", re.IGNORECASE)


def systems_named_in(text: str) -> List[str]:
    """Systems the user named, in the order they appear.

    A catalog phrase that is present names its system. Longer phrases
    claim their span first so a short word inside a longer name does
    not add a second system. Defaults are not applied here.
    """
    raw = (text or "").lower()
    if not raw.strip():
        return []
    phrases: List[Tuple[int, str, str]] = []
    for key, words in _COMMISSIONING_CATALOG:
        for word in words:
            phrases.append((len(word), word, key))
    phrases.sort(key=lambda row: -row[0])
    claimed = [False] * len(raw)
    hits: List[Tuple[int, str]] = []
    seen = set()
    for _n, word, key in phrases:
        for match in re.finditer(rf"(?<![a-z0-9]){re.escape(word)}(?![a-z0-9])", raw):
            start, end = match.span()
            if any(claimed[start:end]):
                continue
            for i in range(start, end):
                claimed[i] = True
            if key not in seen:
                seen.add(key)
                hits.append((start, key))
    hits.sort()
    return [key for _pos, key in hits]


def _name_parts(value: Any) -> List[str]:
    """A list of names, or one comma / 'and'-separated string."""
    if value is None or value == "":
        return []
    if isinstance(value, (list, tuple)):
        return [str(item).strip() for item in value if str(item).strip()]
    text = str(value).strip()
    if not text:
        return []
    return [part.strip() for part in _SPLIT_NAMES.split(text) if part.strip()]


def recognised_and_unknown_systems(value: Any) -> Tuple[List[str], List[str]]:
    """Catalog keys the value names, and leftover names the catalog does not."""
    recognised: List[str] = []
    seen = set()
    unknown: List[str] = []
    for part in _name_parts(value):
        keys = systems_named_in(part)
        if keys:
            for key in keys:
                if key not in seen:
                    seen.add(key)
                    recognised.append(key)
        else:
            unknown.append(part)
    return recognised, unknown


def _checklist_items(checklists: Any, key: str) -> List[Any]:
    if not isinstance(checklists, dict):
        return []
    for alias in _RESULT_KEYS.get(key, (key,)):
        items = checklists.get(alias)
        if isinstance(items, list) and items:
            return items
    return []


def _standard_tests(container: Any, key: str) -> List[Any]:
    fn = getattr(container, _GENERATOR.get(key, ""), None)
    if callable(fn):
        try:
            items = fn()
        except Exception:
            items = None
        if isinstance(items, list) and items:
            return items
    return [{"test": "Standard commissioning tests", "system": key}]


@tool("commissioning_checklist", owner="qaqc", display_name='Commissioning checklist')
async def handle_commissioning_checklist(call: ToolCall) -> dict:
    """The ``commissioning_checklist`` tool."""
    args = call.args
    name = call.name
    agent = call.agent
    user_message = call.user_message
    if "construction" not in agent.allowed_blocks:
        return {
            "name": name, "ok": False,
            "result": {"status": "error", "error": "construction container not in agent's allowed_blocks"},
        }
    try:
        from app.dependencies import get_block_instance
        container = get_block_instance("construction")
    except Exception as e:
        return {
            "name": name, "ok": False,
            "result": {"status": "error", "error": f"construction unavailable: {e}"},
        }
    named = systems_named_in(user_message or args.get("message") or "")
    supplied, unknown = recognised_and_unknown_systems(args.get("systems"))
    if named:
        systems = named
        unknown = []
    elif supplied:
        systems = supplied
    elif unknown:
        systems = []
    else:
        systems = list(_DEFAULT_SYSTEMS)
    try:
        if systems:
            result = await container.commissioning_checklist({}, {"systems": systems})
        else:
            result = {
                "status": "success",
                "checklists_by_system": {},
                "summary": {"systems_covered": 0, "total_tests": 0, "pending": 0},
            }
    except Exception as e:
        return {
            "name": name, "ok": False,
            "result": {"status": "error", "error": f"commissioning_checklist failed: {e}"},
        }
    # Trim the flattened master list — the model only needs the organised
    # per-system checklists + summary to present; the full flat list is
    # redundant and bloats context.
    if isinstance(result, dict):
        result = {k: v for k, v in result.items() if k != "master_test_schedule"}
        by_sys = result.get("checklists_by_system")
        organised = {}
        for key in systems:
            items = _checklist_items(by_sys, key)
            if not items:
                items = _standard_tests(container, key)
            organised[key] = items
        result["checklists_by_system"] = organised
        notes = [row for row in (result.get("notes") or []) if row]
        for leftover in unknown:
            notes.append(f"No standard tests are on file for {leftover}.")
        if notes:
            result["notes"] = notes
        summary = dict(result.get("summary") or {})
        summary["systems_covered"] = len(organised)
        summary["total_tests"] = sum(
            len(items) for items in organised.values() if isinstance(items, list)
        )
        result["summary"] = summary
    return {
        "name": "commissioning_checklist",
        "ok": isinstance(result, dict) and result.get("status") == "success",
        "result": result,
    }
