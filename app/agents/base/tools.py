def calculation_statement(result: dict) -> list[Statement]:
    """What a calculator result states: each numeric output its formula
    DECLARES (``app.lib.formula_registry``: outputs and their units), the
    declared main output first. Nothing is read from a list of names here;
    a formula with no declaration, or a result that is not a success,
    states nothing (the caller then says what was asked and why)."""
    from app.lib import formula_registry

    body = result if isinstance(result, dict) else {}
    # The calculator's own envelope may sit one level down (the tool's
    # ``{"ok", "result": {...}}``); it is the level that names its calculation.
    while not body.get("calculation") and isinstance(body.get("result"), dict):
        body = body["result"]
    if body.get("status") not in (None, "success"):
        return []
    spec = formula_registry.get(str(body.get("calculation") or ""))
    figures = body.get("result") if isinstance(body.get("result"), dict) else body
    if spec is None or not isinstance(figures, dict):
        return []
    source = str(figures.get("standard") or body.get("standard") or "")
    working = str(figures.get("note") or "").strip()
    order = sorted(spec.outputs, key=lambda k: k != spec.main_output)
    out: list[Statement] = []
    for key in order:
        unit = spec.outputs[key]
        value = figures.get(key)
        if unit in ("", "-") or isinstance(value, bool) or not isinstance(value, (int, float)):
            continue
        out.append(Statement(figure=float(value), what=_output_name(key, unit), unit=unit,
                             source=source, working="" if out else working))
    if out and all(st.figure == 0 for st in out):
        # Every declared figure is zero: the calculation ran on inputs that
        # were never given (e.g. an empty call), so it states no figure.
        return []
    return out


def _output_name(key: str, unit: str) -> str:
    """A declared output's name as words: its trailing unit token (the one
    the declaration gives) dropped, underscores read as spaces."""
    words = [w for w in str(key).split("_") if w]
    if len(words) > 1 and words[-1].lower() == str(unit).lower():
        words = words[:-1]
    return " ".join(words)


@tool("construction_calc", owner="base", display_name='Platform calculator',
      kind="computed", statement=calculation_statement, params={
    "calculation": Param(label="which calculation", kind="text", required=True),
    "params": Param(label="calculator inputs", kind="object", required=False),
    "input": Param(label="nested calculator inputs", kind="object", required=False),
})
async def handle_construction_calc(call: ToolCall) -> dict:
    """construction_calc (deterministic formula library)"""
    from app.agents.runtime import (  # noqa: F401 -- runtime helpers, imported at call time
        _ask_is_ipc_certificate,
        _defaulted_run_refusal,
        _dispatch_payment_certificate,
        _formula_calculator_name_from_message,
        _inject_user_ask_into_construction_calc_args,
        _off_loop,
    )
    args = call.args
    history = call.history
    user_message = call.user_message
    calc_name = (
        (args or {}).get("calculation")
        or (args or {}).get("name")
        or (args or {}).get("calculator")
    )
    if (
        not calc_name
        and _ask_is_ipc_certificate(user_message or "")
    ):
        return await _dispatch_payment_certificate(
            args, user_message=user_message,
        )
    # Live Phase-2: the model calls this tool with only
    # ``{"action": "construction_calc"}``. #663 extract reads
    # text/formula/message — inject the current user turn so
    # bind sees As1500 / span 8m / W=10000 kN. D7: never invent.
    args = _inject_user_ask_into_construction_calc_args(
        args, user_message, history=history,
    )
    if not calc_name:
        calc_name = (await _off_loop(_formula_calculator_name_from_message, str((args or {}).get("text") or user_message or ""),
        ))
    from app.lib import construction_formulas as _cf
    calc_params = _cf.coerce_calc_params(args.get("params"))
    # SHARED WITH AGENT C / #636 / #639 / #652: models put calculator
    # kwargs next to ``calculation`` instead of inside ``params``.
    # The container path already flattens; the tool path must too or
    # known names (excavation_bank_m3, volume, BCWS, PMI bcws/bcwp/acwp)
    # never reach run_calculation. Also covers E4 ``text`` / ``formula``.
    # Envelope keys (text/formula/input/project_id) are stripped
    # in bind_calculation_params — never passed as calc kwargs.
    # Unwrap ``input`` the same way as ``params`` (DIR7) — never copy
    # the envelope key itself as a calculator kwarg.
    _envelope = {
        "calculation", "name", "calculator", "params", "input",
        "project_id", "conversation_id", "user_id",
    }
    nested_input = _cf.coerce_calc_params(args.get("input"))
    if nested_input:
        for ik, iv in nested_input.items():
            if ik in _envelope:
                continue
            if ik in calc_params and calc_params[ik] not in (None, ""):
                continue
            if iv is None or iv == "":
                continue
            calc_params[ik] = iv
    for key, val in (args or {}).items():
        if key in _envelope:
            continue
        if key in calc_params and calc_params[key] not in (None, ""):
            continue
        if val is None or val == "":
            continue
        calc_params[key] = val
    from app.core.offload import off_loop_in

    # Parameter extraction and the run are CPU work: never on the event loop,
    # and in the calculator pool, so they never queue ahead of a turn's
    # database reads.
    refusal = await off_loop_in("calc", _defaulted_run_refusal, calc_name, calc_params, user_message)
    if refusal is not None:
        return {"name": "construction_calc", "ok": True, "result": refusal}
    result = await off_loop_in("calc", _cf.run_calculation, calc_name, calc_params)
    return {
        "name": "construction_calc",
        # An ask (status "needs_input") is not a delivered answer, so the tool
        # round is not ok -- same as an "error" (item 7, ORDERS_31OCT_0405Z).
        "ok": isinstance(result, dict) and result.get("status") not in ("error", "needs_input"),
        "result": result,
    }
